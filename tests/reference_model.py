#!/usr/bin/env python3
"""Independent semantic oracle and C-fixture generator for pure-core flow vectors."""

from __future__ import annotations

import argparse
import ipaddress
import json
from pathlib import Path
from typing import Any

UINT64_MAX = (1 << 64) - 1


def saturating_add(left: int, right: int) -> int:
    return min(UINT64_MAX, left + right)


def classify(flow: dict[str, Any], networks: list[ipaddress._BaseNetwork], protocols: dict[tuple[int, int], str]) -> dict[str, Any] | None:
    source = ipaddress.ip_address(flow["orig_src"])
    destination = ipaddress.ip_address(flow["orig_dst"])
    source_local = any(source in network for network in networks)
    destination_local = any(destination in network for network in networks)
    if source_local == destination_local:
        return None

    if source_local:
        host = source
        upload = flow["original"]
        download = flow["reply"]
    else:
        host = destination
        download = flow["original"]
        upload = flow["reply"]

    return {
        "family": flow["family"],
        "ip": str(host),
        "mac": flow["mac"],
        "protocol": protocols.get((flow["l4_proto"], flow["orig_dst_port"]), "Other"),
        "connections": 1 if flow["new_connection"] else 0,
        "download_bytes": download["bytes"],
        "download_packets": download["packets"],
        "upload_bytes": upload["bytes"],
        "upload_packets": upload["packets"],
    }


def evaluate(document: dict[str, Any], scenario: dict[str, Any]) -> list[dict[str, Any]]:
    networks = [ipaddress.ip_network(value, strict=False) for value in document["local_networks"]]
    protocols = {(item["l4_proto"], item["port"]): item["name"] for item in document["protocols"]}
    aggregated: dict[tuple[Any, ...], dict[str, Any]] = {}
    for flow in scenario["flows"]:
        row = classify(flow, networks, protocols)
        if row is None:
            continue
        key = (row["family"], row["ip"], row["mac"], row["protocol"])
        if key not in aggregated:
            aggregated[key] = {**row}
            continue
        current = aggregated[key]
        for field in ("connections", "download_bytes", "download_packets", "upload_bytes", "upload_packets"):
            current[field] = saturating_add(current[field], row[field])
    return sorted(aggregated.values(), key=lambda row: (row["family"], row["ip"], row["mac"] or "", row["protocol"]))


def check(document: dict[str, Any]) -> None:
    for scenario in document["scenarios"]:
        actual = evaluate(document, scenario)
        expected = scenario["expected"]
        if actual != expected:
            raise AssertionError(f'{scenario["name"]}:\nexpected {expected!r}\nactual   {actual!r}')
        print(f'PASS {scenario["name"]}')
    print(f'{len(document["scenarios"])} scenarios passed')


def c_string(value: str | None) -> str:
    if value is None:
        return "NULL"
    return json.dumps(value)


def emit_header(document: dict[str, Any], output: Path) -> None:
    lines = [
        "/* Generated by tests/reference_model.py; do not edit. */",
        "#ifndef TRAFFICMON_GENERATED_VECTORS_H",
        "#define TRAFFICMON_GENERATED_VECTORS_H",
        "",
        "#include <stdbool.h>",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "typedef struct { const char *name; uint8_t l4_proto; uint16_t port; } tm_oracle_protocol;",
        "typedef struct { uint8_t family; uint8_t l4_proto; const char *orig_src; const char *orig_dst; uint16_t orig_src_port; uint16_t orig_dst_port; uint64_t orig_bytes; uint64_t orig_packets; uint64_t reply_bytes; uint64_t reply_packets; const char *mac; bool new_connection; } tm_oracle_flow;",
        "typedef struct { uint8_t family; const char *ip; const char *mac; const char *protocol; uint64_t connections; uint64_t rx_bytes; uint64_t rx_packets; uint64_t tx_bytes; uint64_t tx_packets; } tm_oracle_expected;",
        "typedef struct { const char *name; const tm_oracle_flow *flows; size_t flow_count; const tm_oracle_expected *expected; size_t expected_count; } tm_oracle_scenario;",
        "",
        "static const char *const TM_ORACLE_NETWORKS[] = {",
    ]
    lines.extend(f"    {c_string(network)}," for network in document["local_networks"])
    lines.extend(["};", "", "static const tm_oracle_protocol TM_ORACLE_PROTOCOLS[] = {"])
    lines.extend(
        f'    {{{c_string(item["name"])}, {item["l4_proto"]}, {item["port"]}}},'
        for item in document["protocols"]
    )
    lines.extend(["};", ""])

    for index, scenario in enumerate(document["scenarios"]):
        lines.append(f"static const tm_oracle_flow TM_ORACLE_FLOWS_{index}[] = {{")
        for flow in scenario["flows"]:
            lines.append(
                "    {"
                f'{flow["family"]}, {flow["l4_proto"]}, {c_string(flow["orig_src"])}, {c_string(flow["orig_dst"])}, '
                f'{flow["orig_src_port"]}, {flow["orig_dst_port"]}, {flow["original"]["bytes"]}ULL, '
                f'{flow["original"]["packets"]}ULL, {flow["reply"]["bytes"]}ULL, {flow["reply"]["packets"]}ULL, '
                f'{c_string(flow["mac"])}, {str(flow["new_connection"]).lower()}'
                "},"
            )
        lines.extend(["};", f"static const tm_oracle_expected TM_ORACLE_EXPECTED_{index}[] = {{"])
        for expected in scenario["expected"]:
            lines.append(
                "    {"
                f'{expected["family"]}, {c_string(expected["ip"])}, {c_string(expected["mac"])}, '
                f'{c_string(expected["protocol"])}, {expected["connections"]}ULL, '
                f'{expected["download_bytes"]}ULL, {expected["download_packets"]}ULL, '
                f'{expected["upload_bytes"]}ULL, {expected["upload_packets"]}ULL'
                "},"
            )
        if not scenario["expected"]:
            lines.append("    {0},")
        lines.extend(["};", ""])

    lines.append("static const tm_oracle_scenario TM_ORACLE_SCENARIOS[] = {")
    for index, scenario in enumerate(document["scenarios"]):
        lines.append(
            f'    {{{c_string(scenario["name"])}, TM_ORACLE_FLOWS_{index}, '
            f'sizeof(TM_ORACLE_FLOWS_{index}) / sizeof(TM_ORACLE_FLOWS_{index}[0]), '
            f'TM_ORACLE_EXPECTED_{index}, {len(scenario["expected"])}U}},'
        )
    lines.extend(["};", "", "#endif", ""])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("vectors", type=Path)
    parser.add_argument("--emit-c", type=Path)
    args = parser.parse_args()
    document = json.loads(args.vectors.read_text(encoding="utf-8"))
    check(document)
    if args.emit_c:
        emit_header(document, args.emit_c)


if __name__ == "__main__":
    main()
